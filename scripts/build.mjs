// Pre-renders every formula to MathML with KaTeX so the site needs no math library at runtime.
// Usage: npm install && npm run build   (writes assets/formulas.js)
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { FORMULAS } from '../content/formulas.src.mjs';

const require = createRequire(import.meta.url);
const katex = require('katex');

const render = (tex, display = true) => katex.renderToString(tex, { output: 'mathml', displayMode: display, throwOnError: true, strict: 'ignore' });

const out = FORMULAS.map(f => ({
  ...f,
  html: render(f.tex),
  altHtml: f.alt ? render(f.alt) : null,
  vars: f.vars.map(([sym, meaning, unit]) => ({ sym: render(sym, false), meaning, unit })),
  example: { title: f.example.title, steps: f.example.steps.map(s => render(s)) },
  practice: { ...f.practice, steps: (f.practice.steps || []).map(s => render(s)) }
}));

const js = '/* Generated by scripts/build.mjs from content/formulas.src.mjs. Do not edit by hand. */\n' +
  'window.IC40_FORMULAS = ' + JSON.stringify(out) + ';\n';
writeFileSync(new URL('../assets/formulas.js', import.meta.url), js);
console.log('Rendered ' + out.length + ' formula cards to assets/formulas.js');
